-- ============================================================
-- 01 Site fragment (run once per site schema)
-- Parameter 1 = site code: KHI, LHR or ISB
--
-- Lab 2: HORIZONTAL FRAGMENTATION
--   Each site stores only its own rows of LOG_EVENT.
--   Fragment rule: site_code = '<this site>' (enforced by a CHECK constraint)
-- Lab 7: PARTITIONED TABLE
--   LOG_EVENT is interval partitioned, one partition per day.
-- ============================================================

CREATE TABLE log_event (
  event_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
  site_code   VARCHAR2(3)   DEFAULT '&1' NOT NULL,
  event_time  DATE          NOT NULL,
  asset_id    NUMBER        NOT NULL,
  src_ip      VARCHAR2(15)  NOT NULL,
  src_country VARCHAR2(40),
  dst_port    NUMBER(5),
  event_type  VARCHAR2(20)  NOT NULL,
  action      VARCHAR2(10),
  username    VARCHAR2(40),
  detail      VARCHAR2(200),
  CONSTRAINT log_event_pk PRIMARY KEY (event_id),
  CONSTRAINT log_event_site_ck CHECK (site_code = '&1'),
  CONSTRAINT log_event_type_ck CHECK (event_type IN
    ('LOGIN_OK','LOGIN_FAIL','HTTP_REQ','FW_BLOCK','PORT_SCAN','MALWARE_ALERT','PHISH_CLICK'))
)
PARTITION BY RANGE (event_time)
INTERVAL (NUMTODSINTERVAL(1, 'DAY'))
(PARTITION p_before_2026 VALUES LESS THAN (DATE '2026-01-01'));

-- LOCAL indexes are partitioned the same way as the table
CREATE INDEX log_event_ip_ix   ON log_event (src_ip, event_time) LOCAL;
CREATE INDEX log_event_type_ix ON log_event (event_type, event_time) LOCAL;

-- Lab 2: REPLICATION
-- Copies of central tables that every site needs. Filled by pkg_soc.sync_rules
-- and pkg_soc.block_ip in the central schema.
CREATE TABLE rule_copy (
  rule_id       NUMBER PRIMARY KEY,
  rule_name     VARCHAR2(60),
  event_type    VARCHAR2(20),
  threshold     NUMBER,
  severity      VARCHAR2(10),
  incident_type VARCHAR2(12),
  synced_at     DATE
);

CREATE TABLE blocklist_copy (
  ip         VARCHAR2(15) PRIMARY KEY,
  reason     VARCHAR2(200),
  added_on   DATE,
  synced_at  DATE
);

-- Lab 14: APPLICATION LEVEL AUDITING at the site
-- Logs are evidence, so every update or delete is recorded here.
CREATE TABLE log_change_audit (
  audit_id    NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  event_id    NUMBER,
  src_ip      VARCHAR2(15),
  event_time  DATE,
  change_type VARCHAR2(10),
  db_user     VARCHAR2(30),
  os_user     VARCHAR2(60),
  changed_at  TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE OR REPLACE TRIGGER trg_log_event_change
AFTER UPDATE OR DELETE ON log_event
FOR EACH ROW
DECLARE
  v_change VARCHAR2(10);
BEGIN
  IF DELETING THEN
    v_change := 'DELETE';
  ELSE
    v_change := 'UPDATE';
  END IF;
  INSERT INTO log_change_audit (event_id, src_ip, event_time, change_type, db_user, os_user)
  VALUES (:OLD.event_id, :OLD.src_ip, :OLD.event_time, v_change,
          USER, SYS_CONTEXT('USERENV', 'OS_USER'));
END;
